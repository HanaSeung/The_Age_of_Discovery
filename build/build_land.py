# build_land.py - Natural Earth 10m 해안선 -> land_data.js
# 실행: python build_land.py     (shapely 불필요, 순수 표준 라이브러리)
#
# 형식: 델타 부호화 (2026.07 개정)
#   예전에는 점마다 int16 두 개로 절대좌표(경도x100)를 담았다. int16 은 32,767 이
#   상한이라 경도 180 x scale <= 32767, 즉 scale <= 182 (격자 0.61km) 가 천장이었다.
#   50m 자료는 점 간격이 11km 라 0.01도(1.11km) 격자로도 잃는 점이 8개뿐이었으나,
#   10m 자료는 점 간격이 2km 라 같은 격자에서 5.8%(24,057점)가 겹쳐 사라진다.
#   그래서 '앞 점에서 얼마나 갔는가'만 담는다. 델타는 작아서 대부분 int8 에 들어가고,
#   scale 을 1000(0.111km)으로 올려도 넘치지 않는다. 파일도 절대 int32 의 1/3 이다.
import json, base64, os, struct, urllib.request

SRC = ("https://raw.githubusercontent.com/nvkelso/natural-earth-vector/"
       "master/geojson/ne_10m_land.geojson")
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)      # build\ 의 부모 = 프로젝트 루트
RAW  = os.path.join(ROOT, "raw")  # 다운로드 원문 캐시 자리
os.makedirs(RAW, exist_ok=True)
CACHE = os.path.join(RAW, "ne_10m_land.geojson")
OUT = os.path.join(ROOT, "land_data.js")
NDEC = 3            # 0.001도 = 약 0.111km. NDEC=4 로 올려도 점이 0.07% 늘 뿐이다
SCALE = 10 ** NDEC
MIN_AREA = 0.001    # deg^2, 이보다 작은 폴리곤은 제외 (노이즈 제거)
ESC = -128          # 탈출 부호 — 뒤에 int16 두 개가 온다. 보통 델타는 -127..127

def fetch():
    if os.path.exists(CACHE) and os.path.getsize(CACHE) > 500000:
        print("cache hit:", CACHE); return
    print("downloading Natural Earth 10m land (~10MB) ...")
    urllib.request.urlretrieve(SRC, CACHE)
    print("saved:", CACHE, os.path.getsize(CACHE), "bytes")

def ring_area(pts):
    a = 0.0
    n = len(pts)
    for i in range(n):
        x1, y1 = pts[i][0], pts[i][1]; x2, y2 = pts[(i+1) % n][0], pts[(i+1) % n][1]
        a += x1*y2 - x2*y1
    return abs(a)/2.0

def collect(geom, out):
    t = geom["type"]; c = geom["coordinates"]
    polys = [c] if t == "Polygon" else c
    for poly in polys:
        if not poly: continue
        if ring_area(poly[0]) < MIN_AREA:   # 외곽링 면적으로 판정
            continue
        for ring in poly:
            pts = []; last = None
            for xy in ring:
                q = (round(xy[0], NDEC), round(xy[1], NDEC))
                if q != last:
                    pts.append(q); last = q
            if len(pts) >= 4:
                out.append(pts)

def main():
    fetch()
    d = json.load(open(CACHE, encoding="utf-8"))
    rings = []
    for f in d["features"]:
        collect(f["geometry"], rings)
    npts = sum(len(r) for r in rings)

    # 머리: [uint32 고리수][uint32 길이]*N
    buf = bytearray()
    buf += struct.pack("<I", len(rings))
    for r in rings:
        buf += struct.pack("<I", len(r))

    # 몸: 고리마다 [int32 x0][int32 y0] 뒤에 델타
    nesc = 0
    maxd = 0
    for r in rings:
        px = int(round(r[0][0]*SCALE)); py = int(round(r[0][1]*SCALE))
        buf += struct.pack("<ii", px, py)
        for (x, y) in r[1:]:
            xi = int(round(x*SCALE)); yi = int(round(y*SCALE))
            dx = xi - px; dy = yi - py
            maxd = max(maxd, abs(dx), abs(dy))
            if -127 <= dx <= 127 and -127 <= dy <= 127:
                buf += struct.pack("<bb", dx, dy)
            else:
                assert -32768 <= dx <= 32767 and -32768 <= dy <= 32767, \
                    "델타가 int16 을 넘음 (%d,%d) — 탈출부호를 int32 로 넓혀야 한다" % (dx, dy)
                buf += struct.pack("<bhh", ESC, dx, dy)
                nesc += 1
            px = xi; py = yi

    payload = base64.b64encode(bytes(buf)).decode()
    js = ("// AUTO-GENERATED by build_land.py - DO NOT EDIT BY HAND\n"
          "// Source: Natural Earth 1:10m land (public domain) - naturalearthdata.com\n"
          "// via nvkelso/natural-earth-vector. See SOURCES_LICENSE.md\n"
          "// Format: delta8. Per ring: int32 x0,y0 (lon*%d) then int8 dx,dy;\n"
          "//         dx==-128 escapes to int16 dx,dy. %.3f deg ~ %.3f km. No simplification.\n"
          "window.LANDBIN = { rings: %d, points: %d, scale: %d, format: \"delta8\","
          " data: \"%s\" };\n"
          % (SCALE, 1.0/SCALE, 111.32/SCALE, len(rings), npts, SCALE, payload))
    open(OUT, "w", encoding="utf-8").write(js)
    print("rings: %d | points: %d" % (len(rings), npts))
    print("탈출 %d (%.2f%%) | 최대 델타 %d (%.3f도)"
          % (nesc, 100.0*nesc/max(1, npts-len(rings)), maxd, maxd/float(SCALE)))
    print("binary %d KB -> %s (%d KB)"
          % (len(buf)//1024, OUT, os.path.getsize(OUT)//1024))

if __name__ == "__main__":
    main()
